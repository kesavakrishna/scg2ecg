"""Phase 2 step 6 / Phase 3 bar: the average-heartbeat baseline, scored on development people.

Settings (both score the same 'late' data of each person, see scg2ecg/splits.py):
  unseen  fold-wise: averages from the 10 train people, detector chosen on the 2 tune people
  same    averages and detector from the person's own 'early' data

Rows per setting:
  avg_beat            SCG-detected beats + average ECG beat   (the bar every model must beat)
  avg_beat_true_r     average ECG beat pasted at the true R-peaks (perfect timing: how far timing alone goes)
  real_ecg            the R-peak detector run on the real ECG (ceiling for the beat scores)

Writes results/baselines/{per_person.csv, summary.md, examples.png}.
Run from the repo root:  .venv\\Scripts\\python -m scripts.baselines
"""
from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from scg2ecg.baselines import AverageBeat
from scg2ecg.data import prepared
from scg2ecg.metrics import match_beats, score
from scg2ecg.paths import RESULTS
from scg2ecg.splits import get_splits, segments

FS = 500
OUT = RESULTS / "baselines"


def pieces_for(subject: int, part: str):
    out = []
    for name, a, b in segments(subject, FS)[part]:
        scg, ecg, r = prepared(name, FS)
        rr = r[(r >= a) & (r < b)] - a
        out.append((scg[a:b], ecg[a:b], rr))
    return out


def detector_counts(model: AverageBeat, test) -> dict:
    tp = fn = fp = 0
    for scg, _, r in test:
        det = model.detect(scg)
        ri, _ = match_beats(r, det, FS, 100.0)
        tp, fn, fp = tp + len(ri), fn + len(r) - len(ri), fp + len(det) - len(ri)
    return {"scg_det_se": tp / (tp + fn), "scg_det_ppv": tp / (tp + fp) if tp + fp else float("nan")}


def evaluate(model: AverageBeat, test, setting: str, subject: int, fold) -> tuple[list[dict], dict]:
    targets = [e for _, e, _ in test]
    refs = [r for _, _, r in test]
    preds = [model.predict(scg)[0] for scg, _, _ in test]
    oracle = [model.paste(r, len(e)) for _, e, r in test]
    base = {"setting": setting, "subject": subject, "fold": fold}
    rows = [
        {**base, "method": "avg_beat", "detector": f"{model.mode}@{model.threshold:.2f}",
         **score(targets, preds, refs, FS), **detector_counts(model, test)},
        {**base, "method": "avg_beat_true_r", **score(targets, oracle, refs, FS)},
    ]
    return rows, {"targets": targets, "preds": preds, "refs": refs}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    sp = get_splits()
    rows, examples = [], {}

    for k, fold in enumerate(sp["folds"]):
        model = AverageBeat(FS).fit([p for s in fold["train"] for p in pieces_for(s, "all")])
        f1 = model.tune([p for s in fold["tune"] for p in pieces_for(s, "all")])
        print(f"fold {k}: detector {model.mode}@{model.threshold:.2f} (tune F1 {f1:.3f}), "
              f"{model.n_beats} training beats, envelope offset {model.env_offset * 1000 / FS:.0f} ms")
        for s in fold["test"]:
            test = pieces_for(s, "late")
            r, ex = evaluate(model, test, "unseen", s, k)
            rows += r
            examples[("unseen", s)] = ex
            real = score([e for _, e, _ in test], [e for _, e, _ in test], [r for _, _, r in test], FS)
            rows.append({"setting": "unseen", "subject": s, "fold": k, "method": "real_ecg", **real})

    for s in sp["dev"]:
        early = pieces_for(s, "early")
        model = AverageBeat(FS).fit(early)
        model.tune(early)
        r, ex = evaluate(model, pieces_for(s, "late"), "same", s, None)
        rows += r
        examples[("same", s)] = ex

    df = pd.DataFrame(rows)
    df.to_csv(OUT / "per_person.csv", index=False)

    metrics = ["r", "rmse", "prd", "beat_se", "beat_ppv", "r_timing_abs_ms", "rr_mae_ms"]
    agg = df.groupby(["setting", "method"])[metrics].agg(["mean", "std", "min"])
    flat = df.groupby(["setting", "method"])[metrics + ["scg_det_se", "scg_det_ppv"]].mean().round(3)
    print(flat.to_string())

    # head-to-head: same vs unseen per person, for the avg_beat row
    piv = df[df.method == "avg_beat"].pivot(index="subject", columns="setting", values="r")
    piv["gap"] = piv["same"] - piv["unseen"]
    worst = df[(df.method == "avg_beat") & (df.setting == "unseen")].nsmallest(3, "r")["subject"].tolist()

    lines = [
        "# Average-heartbeat baseline (generated by scripts/baselines.py)", "",
        "Target: lead I ECG, 0.5-40 Hz, z-scored per record, 500 Hz. Test data: each development person's "
        "'late' part (last 30% of the music record after a 10 s gap, plus the after-music record).", "",
        "## Means over the 16 development people", "", flat.to_markdown(), "",
        "## Spread (mean / SD / min across people)", "", agg.round(3).to_markdown(), "",
        "## Per person: r of avg_beat, same-person vs unseen-person", "", piv.round(3).to_markdown(), "",
        f"Three worst people (unseen avg_beat r): {worst}.", "",
        "Columns: r = Pearson; rmse in z-units; prd in %; beat_se / beat_ppv = R-peaks found by neurokit2 in the "
        "output vs the .atr lead I marks (+-150 ms); r_timing_abs_ms = median |timing error| of matched R-peaks; "
        "rr_mae_ms = mean |R-R error| over consecutive matched beats; scg_det_* = the baseline's own SCG beat "
        "detector vs the .atr marks (+-100 ms).",
    ]
    (OUT / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # examples: the three worst people plus two random ones, 6 s each, both settings
    rng = np.random.default_rng(1)
    others = [s for s in sp["dev"] if s not in worst]
    show = worst + [int(x) for x in rng.choice(others, 2, replace=False)]
    W = 6 * FS
    fig, axes = plt.subplots(len(show), 1, figsize=(13, 2.4 * len(show)), sharex=True)
    t = np.arange(W) / FS
    for ax, s in zip(axes, show):
        ex_u, ex_s = examples[("unseen", s)], examples[("same", s)]
        seg = int(np.argmax([len(x) for x in ex_u["targets"]]))
        a = int(rng.integers(0, len(ex_u["targets"][seg]) - W))
        ax.plot(t, ex_u["targets"][seg][a:a + W], color="k", lw=1.0, label="real ECG")
        ax.plot(t, ex_u["preds"][seg][a:a + W], color="#c0392b", lw=0.9, label="avg beat, unseen person")
        ax.plot(t, ex_s["preds"][seg][a:a + W] - 4, color="#2471a3", lw=0.9, label="avg beat, same person (offset)")
        ax.plot(t, ex_u["targets"][seg][a:a + W] - 4, color="k", lw=0.6, alpha=0.5)
        r_u = df[(df.subject == s) & (df.method == "avg_beat") & (df.setting == "unseen")]["r"].iloc[0]
        ax.set_title(f"subject {s}{' (worst 3)' if s in worst else ''}: unseen r={r_u:.2f}", fontsize=8, loc="left")
        ax.set_yticks([])
    axes[0].legend(fontsize=7, loc="upper right", ncol=3)
    axes[-1].set_xlabel("seconds (random 6 s of the test part)")
    fig.tight_layout()
    fig.savefig(OUT / "examples.png", dpi=90)
    plt.close(fig)
    print("\n".join(lines[-8:]))


if __name__ == "__main__":
    main()
