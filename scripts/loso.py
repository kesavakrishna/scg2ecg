"""Follow-up 3 (exploratory): leave one development person out, 16 times.

The holdout reversed the development result (U-Net vs average-beat baseline, no calibration). The development folds
trained on 10 people; the holdout models on 16. Here each of the 16 development people is tested with models trained
on the other 15: the U-Net with the holdout phase's fixed rule (2 epochs, no early stopping, seeds 0-2) and the
average-beat baseline fitted and tuned on the same 15. Test data: the person's 'late' part.

Exploratory: these 16 people have been looked at throughout development, and nothing here can replace the holdout.

Writes results/loso/{per_person.csv, summary.md}.
Run from the repo root:  .venv\\Scripts\\python -m scripts.loso
"""
from __future__ import annotations

import time

import numpy as np
import pandas as pd
from scipy.stats import wilcoxon

from scg2ecg.baselines import AverageBeat
from scg2ecg.metrics import morphology, score
from scg2ecg.paths import RESULTS
from scg2ecg.splits import get_splits, segments
from scg2ecg.windows import stitch_predict

from .calibration import avg_beat_pieces, raw_piece
from .simple_models import DEV, FS, LEN, SEEDS, segs, train_unet

OUT = RESULTS / "loso"
EPOCHS = 2  # the holdout plan's rule for the U-Net (median early-stopping epoch + 1)
METRICS = ["r", "beat_se", "beat_ppv", "r_timing_abs_ms", "template_r", "beat_r", "r_amp_ratio"]


def run(sp):
    path = OUT / "per_person.csv"
    rows = pd.read_csv(path).to_dict("records") if path.exists() else []
    done = {r["subject"] for r in rows}
    for s in sp["dev"]:
        if s in done:
            continue
        t0 = time.time()
        others = [p for p in sp["dev"] if p != s]
        test = segs([s], "late")
        args0 = ([t["y"] for t in test], None, [t["r"] for t in test], FS)
        ab = AverageBeat(FS).fit(avg_beat_pieces(others, "all"))
        ab.tune(avg_beat_pieces(others, "all"))
        preds = [ab.predict(raw_piece(sg)[0])[0] for sg in segments(s, FS)["late"]]
        a = (args0[0], preds, args0[2], FS)
        rows.append({"subject": s, "method": "avg_beat", "seed": None, **score(*a), **morphology(*a)})
        train = segs(others, "all")
        for seed in SEEDS:
            model, _, _ = train_unet(train, None, seed, max_epochs=EPOCHS, patience=10 ** 6)
            preds = [stitch_predict(model, t["x"], LEN, DEV) for t in test]
            a = (args0[0], preds, args0[2], FS)
            rows.append({"subject": s, "method": "unet", "seed": seed, **score(*a), **morphology(*a)})
        print(f"subject {s} done ({(time.time() - t0) / 60:.1f} min)", flush=True)
        pd.DataFrame(rows).to_csv(path, index=False)


def summarize():
    df = pd.read_csv(OUT / "per_person.csv")
    pp = df.groupby(["method", "subject"])[METRICS].mean().reset_index()
    table = pp.groupby("method")[METRICS].mean().round(3)
    piv = pp.pivot(index="subject", columns="method", values="r")
    d = piv["unet"] - piv["avg_beat"]
    folds = pd.read_csv(RESULTS / "gans" / "per_person.csv")
    fold_r = folds[folds.method.isin(["unet", "avg_beat"])].groupby(["method", "subject"]).r.mean().unstack(0)
    cmp = pd.DataFrame({"folds (train on 10): unet": fold_r["unet"], "folds: avg_beat": fold_r["avg_beat"],
                        "LOSO (train on 15): unet": piv["unet"], "LOSO: avg_beat": piv["avg_beat"]}).round(3)
    lines = ["# Leave one development person out (generated by scripts/loso.py) - exploratory", "",
             "Each development person is tested with models trained on the other 15 (U-Net: 2 epochs, 3 seeds; "
             "average-beat baseline fitted and tuned on the same 15). Test data: the person's 'late' part.", "",
             "## Means over the 16 development people", "", table.to_markdown(), "",
             f"- unet vs avg_beat: unet better for {(d > 0).sum()} of {len(d)} people; mean r difference {d.mean():+.3f}; "
             f"Wilcoxon p = {wilcoxon(d).pvalue:.3g}", "",
             "## Per person: 4 folds (10 training people) vs leave-one-out (15)", "", cmp.to_markdown(), "",
             f"Means: {cmp.mean().round(3).to_dict()}", ""]
    (OUT / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    run(get_splits())
    summarize()


if __name__ == "__main__":
    main()
