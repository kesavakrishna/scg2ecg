"""C7: a heartbeat check that copes with irregular rhythms. No models needed (CPU).

The periodicity gate (scripts/gate.py) passes only 64% of real windows for the person with the most irregular rhythm.
Here it is compared with beat_consistency (scg2ecg/gate.py: do the detected vibration beats look alike, whenever
they come?), with the two combined (pass if either passes), and with the proposed rule: periodicity, or consistency
together with beat_regularity (most intervals between detected beats within 20% of the median). Same folds, thresholds (95% of the 2 tune people's
real windows) and negatives as scripts/gate.py. Real windows are also split by whether they contain an irregular beat
(R-R differs >20% from the local median, from the database's R-peak marks).

Writes results/gate2/{windows.csv, summary.md}.
Run from the repo root:  .venv\\Scripts\\python -m scripts.gate2
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from scg2ecg.gate import beat_consistency, beat_regularity, periodicity, windows
from scg2ecg.paths import RESULTS
from scg2ecg.splits import get_splits

from .clinical import irregular_flags
from .gate import NEG_SECONDS, colored_noise, shuffled
from .simple_models import FS, segs

OUT = RESULTS / "gate2"
SCORES = ("periodicity", "consistency", "regularity")


def score(x, r=None):
    out = []
    flags = irregular_flags(r) if r is not None else None
    for a, b in windows(len(x), FS):
        row = {"periodicity": periodicity(x[a:b], FS), "consistency": beat_consistency(x[a:b], FS),
               "regularity": beat_regularity(x[a:b], FS)}
        if r is not None:
            inside = (r >= a) & (r < b)
            row["irregular_window"] = bool(flags[inside].any())
        out.append(row)
    return out


def run(sp) -> pd.DataFrame:
    rows = []
    for k, fold in enumerate(sp["folds"]):
        for s in fold["tune"]:
            for t in segs([s], "late"):
                rows += [{"fold": k, "subject": s, "role": "threshold", "input": "real", **r} for r in score(t["x"], t["r"])]
        for s in fold["test"]:
            rng = np.random.default_rng(1000 * k + s)
            test = segs([s], "late")
            for t in test:
                rows += [{"fold": k, "subject": s, "role": "test", "input": "real", **r} for r in score(t["x"], t["r"])]
            x = test[0]["x"][:NEG_SECONDS * FS]
            n = len(x)
            negs = {"white_noise": colored_noise(n, rng, 0), "pink_noise": colored_noise(n, rng, 1),
                    "brown_noise": colored_noise(n, rng, 2), "shuffled_50ms": shuffled(x, 0.05, rng),
                    "shuffled_200ms": shuffled(x, 0.2, rng)}
            for name, xi in negs.items():
                rows += [{"fold": k, "subject": s, "role": "test", "input": name, **r} for r in score(xi)]
        print(f"fold {k} done", flush=True)
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "windows.csv", index=False)
    return df


def apply_thresholds(df: pd.DataFrame) -> pd.DataFrame:
    out = []
    for k, g in df.groupby("fold"):
        tr = g[(g.role == "threshold") & (g.input == "real")]
        te = g[g.role == "test"].copy()
        for c in SCORES:
            te[f"pass_{c}"] = te[c] >= tr[c].quantile(0.05)
        te["pass_either"] = te.pass_periodicity | te.pass_consistency
        # the proposed rule: a repeating signal, or alike beats at mostly regular intervals
        te["pass_combined"] = te.pass_periodicity | (te.pass_consistency & te.pass_regularity)
        out.append(te)
    return pd.concat(out)


def summarize(df: pd.DataFrame):
    te = apply_thresholds(df)
    cols = ["pass_periodicity", "pass_consistency", "pass_either", "pass_combined"]
    order = ["real", "white_noise", "pink_noise", "brown_noise", "shuffled_50ms", "shuffled_200ms"]
    rates = te.groupby(["input", "subject"])[cols].mean().groupby("input").mean().reindex(order).round(3)
    real = te[te.input == "real"]
    irr = real.groupby("irregular_window")[cols].mean().round(3)
    irr.insert(0, "windows", real.groupby("irregular_window").size())
    per = real.groupby("subject")[cols].mean().round(2)
    lines = ["# A heartbeat check for irregular rhythms (generated by scripts/gate2.py)", "",
             "8 s windows of the 16 development people as unseen people; thresholds per fold from the 2 tune "
             "people (95% of their real windows pass). Pass rates per person, then averaged.", "",
             "## Fraction of windows that pass", "", rates.to_markdown(), "",
             "## Real windows with and without an irregular beat", "", irr.to_markdown(), "",
             "## Per person, real windows", "", per.T.to_markdown(), ""]
    (OUT / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    summarize(run(get_splits()))


if __name__ == "__main__":
    main()
