"""C8: a per-beat confidence score from seed disagreement. Unseen-person setting, 16 CEBS development people.

For each beat (database R-peak marks, -250..+450 ms) of each person's 'late' part, with the person's fold models:
  output   the mean of the 3 seeds' outputs (what would be shown)
  conf     mean pairwise correlation of the 3 seeds' beats (high = the seeds agree)
  quality  correlation of the output beat with the real beat
Questions: does conf rank beats by quality (Spearman, pooled and within person)? If the least confident 10/20/30% of
beats are hidden, how good are the remaining ones?

Writes results/confidence/{beats.csv, summary.md, reliability.png}.
Run from the repo root:  .venv\\Scripts\\python -m scripts.confidence
"""
from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from scipy.stats import spearmanr

from scg2ecg.gate import seed_agreement
from scg2ecg.metrics import pearson
from scg2ecg.paths import RESULTS
from scg2ecg.splits import get_splits
from scg2ecg.windows import stitch_predict

from .calibration import load_unet
from .simple_models import DEV, FS, LEN, SEEDS, segs

OUT = RESULTS / "confidence"
PRE, POST = int(0.25 * FS), int(0.45 * FS)


def run(sp) -> pd.DataFrame:
    rows = []
    for k, fold in enumerate(sp["folds"]):
        models = [load_unet(k, s) for s in SEEDS]
        for s in fold["test"]:
            for i, t in enumerate(segs([s], "late")):
                preds = [stitch_predict(m, t["x"], LEN, DEV) for m in models]
                out = np.mean(preds, 0)
                r = t["r"][(t["r"] > PRE) & (t["r"] < len(t["y"]) - POST)]
                for b in r:
                    w = slice(b - PRE, b + POST)
                    rows.append({"fold": k, "subject": s, "segment": i, "r_mark": int(b),
                                 "conf": seed_agreement([p[w] for p in preds]),
                                 "quality": pearson(t["y"][w], out[w])})
        print(f"fold {k} done", flush=True)
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "beats.csv", index=False)
    return df


def summarize(df: pd.DataFrame):
    pooled = spearmanr(df.conf, df.quality).correlation
    within = df.groupby("subject").apply(lambda g: spearmanr(g.conf, g.quality).correlation)
    lines = ["# Per-beat confidence from seed disagreement (generated by scripts/confidence.py)", "",
             f"{len(df)} beats of 16 unseen development people. conf = mean pairwise r of the 3 seeds' beats; "
             "quality = r of the 3-seed mean beat with the real beat.", "",
             f"- Spearman(conf, quality), all beats pooled: {pooled:.3f}",
             f"- within a person: median {within.median():.3f} (range {within.min():.3f} to {within.max():.3f})", ""]
    rows = []
    for hide in (0.0, 0.1, 0.2, 0.3):
        # threshold set over all beats pooled: the device hides its least confident beats, whoever they belong to
        th = df.conf.quantile(hide)
        kept = df[df.conf >= th]
        per = kept.groupby("subject").quality.median()
        rows.append({"hidden": f"{hide:.0%}", "beats kept": len(kept), "median quality of kept beats":
                     round(kept.quality.median(), 3), "share of kept beats with quality < 0.5":
                     round((kept.quality < 0.5).mean(), 3), "people with no beats left":
                     int(16 - per.size)})
    lines += ["## Hiding the least confident beats", "", pd.DataFrame(rows).to_markdown(index=False), "",
              "## Within-person Spearman", "", within.round(3).to_frame("spearman").T.to_markdown(), ""]
    (OUT / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))

    df = df.copy()
    df["bin"] = pd.qcut(df.conf, 10, duplicates="drop")
    b = df.groupby("bin", observed=True).agg(conf=("conf", "mean"), q=("quality", "median"),
                                            q25=("quality", lambda v: v.quantile(0.25)),
                                            q75=("quality", lambda v: v.quantile(0.75)))
    fig, ax = plt.subplots(figsize=(6, 4.5))
    ax.fill_between(b.conf, b.q25, b.q75, color="#aed6f1", label="middle 50% of beats")
    ax.plot(b.conf, b.q, "o-", color="#1a5276", label="median")
    ax.set_xlabel("confidence: agreement of 3 seeds on the beat (decile means)")
    ax.set_ylabel("beat quality: r with the real beat")
    ax.legend(fontsize=8)
    ax.set_title("Unseen CEBS people, no calibration", fontsize=9)
    fig.tight_layout()
    fig.savefig(OUT / "reliability.png", dpi=100)
    plt.close(fig)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    summarize(run(get_splits()))


if __name__ == "__main__":
    main()
