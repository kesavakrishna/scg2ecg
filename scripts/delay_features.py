"""B6: can features of the SCG alone predict a person's timing offset (no ECG at all)?

Phase 4 showed that much of the unseen-person error is a constant shift: the U-Net draws the R-wave too early or too
late for some people. The shift that fits best was measured with each person's ECG in the calibration experiments:
  CEBS          16 development people, fold U-Nets, shift fitted on 60 s (results/calibration, unet_shift)
  SensSmartTech 31 people, CEBS final U-Net, shift fitted on 26 s (results/external, unet_shift)
Here, features of the SCG alone (same clips) try to predict that shift, leave one person out (ridge regression on
standardised features). Compared with no shift and with always applying the training people's mean shift.

Features (from the SCG's 5-30 Hz energy envelope, beats found as envelope peaks): heart rate; width of the main
envelope peak; lag and relative height of the second envelope peak (the diastolic complex); SCG spectral centroid.

Writes results/delay_features/{per_person.csv, summary.md}.
Run from the repo root:  .venv\\Scripts\\python -m scripts.delay_features
"""
from __future__ import annotations

import numpy as np
import pandas as pd
from scipy.signal import find_peaks
from scipy.stats import spearmanr
from sklearn.linear_model import Ridge

from scg2ecg.data import prepared
from scg2ecg.gate import envelope
from scg2ecg.paths import RESULTS
from scg2ecg.splits import get_splits

from .calibration import calib_segment
from .external import load_rec, recordings

OUT = RESULTS / "delay_features"
FS = 500
FEATURES = ["hr", "main_width_ms", "second_lag_ms", "second_ratio", "centroid_hz"]


def features(scg: np.ndarray) -> dict:
    e = envelope(scg, FS)
    pk, _ = find_peaks(e, distance=int(0.4 * FS), prominence=0.3 * np.percentile(e, 95))
    pk = pk[(pk > int(0.3 * FS)) & (pk < len(e) - int(0.7 * FS))]
    if len(pk) < 3:
        return {f: np.nan for f in FEATURES}
    beats = np.stack([e[p - int(0.3 * FS):p + int(0.7 * FS)] for p in pk])
    avg = beats.mean(0)
    c = int(0.3 * FS)
    half = avg[c] / 2
    lo = c - np.argmax(avg[c::-1] < half)
    hi = c + np.argmax(avg[c:] < half)
    a, b = c + int(0.15 * FS), c + int(0.45 * FS)
    j = a + int(np.argmax(avg[a:b]))
    spec = np.abs(np.fft.rfft(scg - scg.mean())) ** 2
    f = np.fft.rfftfreq(len(scg), 1 / FS)
    band = (f >= 1) & (f <= 40)
    return {"hr": 60.0 / (np.median(np.diff(pk)) / FS), "main_width_ms": (hi - lo) * 1000 / FS,
            "second_lag_ms": (j - c) * 1000 / FS, "second_ratio": avg[j] / avg[c],
            "centroid_hz": float((f[band] * spec[band]).sum() / spec[band].sum())}


def cebs_rows() -> list[dict]:
    cal = pd.read_csv(RESULTS / "calibration" / "per_person.csv")
    sh = cal[(cal.method == "unet_shift") & (cal.calib_s == 60)].groupby("subject").shift_ms.mean()
    rows = []
    for s in get_splits()["dev"]:
        name, a, b = calib_segment(s, 60)
        scg = prepared(name, FS)[0][a:b]
        rows.append({"dataset": "CEBS", "subject": s, "shift_ms": sh[s], **features(scg)})
    return rows


def sst_rows() -> list[dict]:
    ext = pd.read_csv(RESULTS / "external" / "per_recording.csv")
    sh = ext[(ext.method == "unet_shift") & (ext.calib_s == 26)].groupby("subject").shift_ms.mean()
    recs = recordings()
    rows = []
    for s, g in recs.groupby("subject"):
        if s not in sh:
            continue
        first = g[g.state == "B"].iloc[0]
        rows.append({"dataset": "SensSmartTech", "subject": s, "shift_ms": sh[s], **features(load_rec(first.to_dict())["scg"])})
    return rows


def loo(df: pd.DataFrame) -> dict:
    X, y = df[FEATURES].to_numpy(float), df.shift_ms.to_numpy(float)
    pred, mean_pred = np.zeros(len(y)), np.zeros(len(y))
    for i in range(len(y)):
        tr = np.arange(len(y)) != i
        mu, sd = X[tr].mean(0), X[tr].std(0) + 1e-9
        m = Ridge(alpha=1.0).fit((X[tr] - mu) / sd, y[tr])
        pred[i] = m.predict(((X[i] - mu) / sd)[None])[0]
        mean_pred[i] = y[tr].mean()
    return {"people": len(y), "MAE no shift": np.abs(y).mean(), "MAE training mean": np.abs(y - mean_pred).mean(),
            "MAE SCG features (LOO)": np.abs(y - pred).mean(), "Spearman(pred, actual)": spearmanr(pred, y).correlation}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    df = pd.DataFrame(cebs_rows() + sst_rows()).dropna()
    df.to_csv(OUT / "per_person.csv", index=False)
    res = pd.DataFrame({d: loo(g) for d, g in df.groupby("dataset")}).T.round(2)
    corr = df.groupby("dataset").apply(lambda g: pd.Series({f: spearmanr(g[f], g.shift_ms).correlation
                                                             for f in FEATURES})).round(2)
    lines = ["# Predicting the timing offset from the SCG alone (generated by scripts/delay_features.py)", "",
             "shift_ms: the shift of the U-Net output that best matches the real ECG, measured on a calibration clip "
             "(positive = output late). Mean absolute error in ms of three ways to guess it without any ECG.", "",
             res.to_markdown(), "",
             "## Spearman correlation of each feature with the shift", "", corr.to_markdown(), ""]
    (OUT / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
